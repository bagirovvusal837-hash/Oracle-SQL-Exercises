-- BÖLÜM 17: DATABASE VIEWS
CREATE OR REPLACE VIEW v_customer_accounts AS SELECT c.full_name, c.cif, a.account_no, a.currency, a.balance, b.branch_name FROM customers c JOIN accounts a ON c.cif = a.cif JOIN branches b ON a.branch_code = b.branch_code;
CREATE OR REPLACE VIEW v_customer_total_balance AS SELECT c.cif, c.full_name, SUM(a.balance) as umumi_balans FROM customers c JOIN accounts a ON c.cif = a.cif GROUP BY c.cif, c.full_name;
CREATE OR REPLACE VIEW v_overdue_loans AS SELECT loan_id, cif, account_no, loan_amount, principal_debt, interest_debt, penalty_debt, status FROM loans WHERE status = 'OVERDUE';
CREATE OR REPLACE VIEW v_monthly_transactions AS SELECT TO_CHAR(txn_date, 'yyyy-mm') as ay, COUNT(*) as transaksiya_sayi, SUM(amount) as toplam_mebleg FROM transactions GROUP BY TO_CHAR(txn_date, 'yyyy-mm');
