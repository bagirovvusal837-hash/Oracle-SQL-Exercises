-- BÖLÜM 2: BRANCHES
CREATE TABLE BRANCHES (
    branch_code NUMBER PRIMARY KEY,
    branch_name VARCHAR2(100) NOT NULL,
    city VARCHAR2(50) NOT NULL,
    opened_date DATE DEFAULT SYSDATE,
    status VARCHAR2(10) CHECK (status IN ('ACTIVE', 'CLOSED')),
    director VARCHAR2(100)
);

-- BÖLÜM 3: CUSTOMERS
CREATE TABLE CUSTOMERS (
    cif NUMBER PRIMARY KEY,
    full_name VARCHAR2(150) NOT NULL,
    customer_type CHAR(1) CHECK (customer_type IN ('I', 'C')),
    pin VARCHAR2(20),
    voen VARCHAR2(20) UNIQUE,
    phone VARCHAR2(20),
    email VARCHAR2(100) UNIQUE,
    birth_date DATE,
    created_at DATE DEFAULT SYSDATE,
    status VARCHAR2(10) CHECK (status IN ('ACTIVE', 'CLOSED', 'BLOCKED'))
);

-- BÖLÜM 4: ACCOUNTS
CREATE TABLE ACCOUNTS (
    account_no VARCHAR2(20) PRIMARY KEY,
    cif NUMBER,
    branch_code NUMBER,
    currency CHAR(3) CHECK (currency IN ('AZN','USD','EUR')),
    balance NUMBER DEFAULT 0 CHECK(balance >= 0),
    opened_date DATE DEFAULT SYSDATE,
    status VARCHAR2(10) CHECK(status IN ('ACTIVE','CLOSED','BLOCKED')),
    CONSTRAINT fk_accounts_customers FOREIGN KEY(cif) REFERENCES customers(cif),
    CONSTRAINT fk_accounts_branches FOREIGN KEY(branch_code) REFERENCES branches(branch_code)
);

-- BÖLÜM 5: TRANSACTIONS
CREATE TABLE TRANSACTIONS (
    txn_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_no VARCHAR2(20),
    txn_type VARCHAR2(10) CHECK (txn_type IN ('DEBIT','CREDIT')),
    amount NUMBER CHECK (amount > 0),
    currency CHAR(3) CHECK (currency IN ('AZN','USD','EUR')),
    txn_date DATE DEFAULT SYSDATE,
    description VARCHAR2(250),
    CONSTRAINT fk_txns_accounts FOREIGN KEY(account_no) REFERENCES accounts(account_no)
);

-- BÖLÜM 6: LOANS
CREATE TABLE LOANS (
    loan_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cif NUMBER,
    account_no VARCHAR2(20),
    loan_amount NUMBER CHECK (loan_amount > 0),
    interest_rate NUMBER CHECK (interest_rate > 0),
    principal_debt NUMBER DEFAULT 0,
    interest_debt NUMBER DEFAULT 0,
    penalty_debt NUMBER DEFAULT 0,
    start_date DATE DEFAULT SYSDATE,
    end_date DATE,
    status VARCHAR2(10) CHECK(status IN('ACTIVE','CLOSED','OVERDUE')),
    CONSTRAINT fk_loans_accounts FOREIGN KEY (account_no) REFERENCES accounts(account_no),
    CONSTRAINT fk_loan_dates CHECK(end_date > start_date)
);

-- BÖLÜM 7: CARDS
CREATE TABLE CARDS (
    card_no VARCHAR2(16) PRIMARY KEY,
    account_no VARCHAR2(20) NOT NULL,
    card_type VARCHAR2(10) CHECK(card_type IN ('DEBIT','CREDIT')),
    expire_date DATE NOT NULL,
    status VARCHAR2(10) CHECK(status IN('ACTIVE','BLOCKED','EXPIRED')),
    CONSTRAINT fk_cards_accounts FOREIGN KEY(account_no) REFERENCES accounts(account_no)
);

-- BÖLÜM 8: SEQUENCES
CREATE SEQUENCE seq_txn_id START WITH 1 INCREMENT BY 1 NOCACHE;
CREATE SEQUENCE seq_loan_id START WITH 1 INCREMENT BY 1 NOCACHE;

-- BÖLÜM 9: TRIGGERS
CREATE OR REPLACE TRIGGER trg_transactions_bi BEFORE INSERT ON transactions FOR EACH ROW
BEGIN
    IF :NEW.txn_id IS NULL THEN SELECT seq_txn_id.nextval INTO :NEW.txn_id FROM dual; END IF;
END;
/
CREATE OR REPLACE TRIGGER trg_loans_auto_id BEFORE INSERT ON loans FOR EACH ROW
BEGIN
    IF :NEW.loan_id IS NULL THEN SELECT seq_loan_id.nextval INTO :NEW.loan_id FROM dual; END IF;
END;
/

-- BÖLÜM 10: INDEXES
CREATE INDEX idx_accounts_cif ON accounts(cif);
CREATE INDEX idx_accounts_branch_code ON accounts(branch_code);
CREATE INDEX idx_transactions_account_no ON transactions(account_no);
CREATE INDEX idx_transactions_txn_date ON transactions(txn_date);
CREATE INDEX idx_loans_cif ON loans(cif);
CREATE INDEX idx_loans_account_no ON loans(account_no);
CREATE INDEX idx_cards_account_no ON cards(account_no);

