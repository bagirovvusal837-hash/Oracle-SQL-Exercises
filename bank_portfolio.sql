-- BÖLÜM 13: JOINS & GROUP BY
SELECT c.full_name, a.account_no, a.currency, a.balance FROM customers c JOIN accounts a ON c.cif = a.cif;
SELECT a.account_no, b.branch_name, b.city FROM accounts a JOIN branches b ON a.branch_code = b.branch_code;
SELECT c.full_name, l.loan_id, l.loan_amount, l.status FROM customers c JOIN loans l ON c.cif = l.cif;
SELECT a.account_no, t.txn_id, t.txn_type, t.amount, t.txn_date FROM accounts a JOIN transactions t ON a.account_no = t.account_no;
SELECT c.card_no, c.status, cu.full_name FROM cards c JOIN accounts a ON c.account_no = a.account_no JOIN customers cu ON a.cif = cu.cif;
SELECT b.branch_name, COUNT(DISTINCT a.cif) AS musteri_sayi FROM branches b JOIN accounts a ON b.branch_code = a.branch_code GROUP BY b.branch_name;
SELECT b.branch_name, COUNT(a.account_no) AS hesab_sayi FROM branches b JOIN accounts a ON b.branch_code = a.branch_code GROUP BY b.branch_name;
SELECT c.full_name, SUM(a.balance) AS umumi_balans FROM customers c JOIN accounts a ON c.cif = a.cif GROUP BY c.full_name;
SELECT c.full_name, c.cif, l.loan_amount, l.status FROM customers c JOIN loans l ON c.cif = l.cif;
SELECT DISTINCT cu.full_name, cu.cif FROM customers cu JOIN accounts a ON cu.cif = a.cif JOIN cards ca ON a.account_no = ca.account_no WHERE cu.cif NOT IN (SELECT cif FROM loans WHERE cif IS NOT NULL);

-- BÖLÜM 14: AGGREGATIONS
SELECT currency, SUM(balance) AS toplam_balans FROM accounts GROUP BY currency;
SELECT branch_code, SUM(balance) AS filial_toplam_balans FROM accounts GROUP BY branch_code;
SELECT customer_type, COUNT(*) AS musteri_sayi FROM customers GROUP BY customer_type;
SELECT account_no, COUNT(*) AS transaksiya_sayi FROM transactions GROUP BY account_no;
SELECT account_no, txn_type, SUM(amount) AS toplam_mebleg FROM transactions GROUP BY account_no, txn_type;
SELECT account_no, COUNT(*) AS transaksiya_sayi FROM transactions GROUP BY account_no HAVING COUNT(*) > 3;
SELECT cif, SUM(balance) AS toplam_balans FROM accounts GROUP BY cif HAVING SUM(balance) > 5000;
SELECT status, COUNT(*) AS hesab_sayi FROM accounts GROUP BY status;
SELECT status, SUM(loan_amount) AS toplam_kredit_meblegi FROM loans GROUP BY status;
SELECT TO_CHAR(txn_date, 'yyyy-mm') AS ay, COUNT(*) AS transaksiya_sayi, SUM(amount) AS toplam_mebleg FROM transactions GROUP BY TO_CHAR(txn_date, 'yyyy-mm');

-- BÖLÜM 15: WINDOW FUNCTIONS
SELECT * FROM (SELECT account_no, txn_id, txn_type, amount, txn_date, ROW_NUMBER() OVER (PARTITION BY account_no ORDER BY txn_date DESC) as rn FROM transactions) WHERE rn = 1;
SELECT * FROM (SELECT account_no, branch_code, balance, currency, ROW_NUMBER() OVER (PARTITION BY branch_code ORDER BY balance DESC) as rank FROM accounts) WHERE rank <= 3;
SELECT account_no, currency, balance, DENSE_RANK() OVER (PARTITION BY currency ORDER BY balance DESC) AS valyuta_ranki FROM accounts;
SELECT cif, account_no, currency, balance, ROW_NUMBER() OVER (PARTITION BY cif ORDER BY balance DESC) AS musteri_ici_sira FROM accounts;
SELECT account_no, txn_id, txn_date, amount, txn_type, SUM(CASE WHEN txn_type = 'CREDIT' THEN amount ELSE -amount END) OVER (PARTITION BY account_no ORDER BY txn_date ROWS BETWEEN UNBOUNDED PRECEDING AND CURRENT ROW) as running_balance FROM transactions;
WITH m_data AS (SELECT TO_CHAR(txn_date, 'yyyy-mm') as ay, SUM(amount) as c_toplam FROM transactions GROUP BY TO_CHAR(txn_date, 'yyyy-mm')) SELECT ay, c_toplam, LAG(c_toplam, 1) OVER (ORDER BY ay) as e_toplam, (c_toplam - LAG(c_toplam, 1) OVER (ORDER BY ay)) as ferq FROM m_data;
SELECT * FROM (SELECT cif, account_no, currency, balance, ROW_NUMBER() OVER (PARTITION BY cif ORDER BY balance DESC) as rn FROM accounts) WHERE rn = 1;
SELECT loan_id, cif, loan_amount, interest_rate, DENSE_RANK() OVER (ORDER BY interest_rate DESC) as faiz_ranki FROM loans;
SELECT b.branch_name, a.cif, SUM(a.balance) as toplam_balans, DENSE_RANK() OVER (PARTITION BY a.branch_code ORDER BY SUM(a.balance) DESC) as filial_ici_musteri_ranki FROM accounts a JOIN branches b ON a.branch_code = b.branch_code GROUP BY b.branch_name, a.branch_code, a.cif;
SELECT account_no, txn_date as son_txn_tarixi, TRUNC(SYSDATE - txn_date) as kecen_gun_sayi FROM (SELECT account_no, txn_date, ROW_NUMBER() OVER (PARTITION BY account_no ORDER BY txn_date DESC) as rn FROM transactions) WHERE rn = 1;

